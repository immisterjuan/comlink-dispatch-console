const REMOTE_MARKER_BG = '#4CAF50';
const REMOTE_MARKER_FG = '#FFFFFF';

// tracker type name -> MDI icon key (mirrors TRACKER_TYPES[].icon)
const TYPE_ICONS: Record<string, string> = {
  person: 'account',
  vehicle: 'car',
  boat: 'ferry',
  aircraft: 'airplane',
  building: 'office-building',
  checkpoint: 'map-marker-check',
  'aid-station': 'medical-bag',
  ambulance: 'ambulance',
  security: 'shield-account',
};

export const TRACKER_TYPE_BADGES: Record<string, TrackerBadge> = Object.keys(TYPE_ICONS).reduce(
  (acc, name) => {
    const icon = ICON_PATHS[TYPE_ICONS[name]] || ICON_PATHS.account;
    acc[name] = { color: REMOTE_MARKER_BG, fg: REMOTE_MARKER_FG, svg: icon };
    return acc;
  },
  {} as Record<string, TrackerBadge>,
);

export const getTrackerBadge = (type?: string): TrackerBadge =>
  TRACKER_TYPE_BADGES[type || 'person'] || TRACKER_TYPE_BADGES.person;
